it('retains caret, scroll, find settings and undo across file remounts, including external AI edits', async () => {
  const handle = createRef<LatexSourceHandle>()
  function Harness() {
    const [text, setText] = useState('first\nsecond')
    const [visible, setVisible] = useState(true)
    return <><button onClick={() => setVisible(!visible)}>Switch file</button><button onClick={() => setText('AI result')}>Apply AI</button>{visible && <LatexSourceEditor ref={handle} sessionKey="session-test" value={text} onChange={setText} />}</>
  }
  render(<Harness />)
  let input = screen.getByLabelText<HTMLTextAreaElement>('latex.source')
  input.setSelectionRange(6, 6)
  fireEvent.select(input)
  fireEvent.keyDown(input, { key: 'Tab' })
  await waitFor(() => expect(input.selectionStart).toBe(8))
  input.scrollTop = 45
  fireEvent.scroll(input)
  fireEvent.keyDown(input, { key: 'f', metaKey: true })
  fireEvent.change(screen.getByRole('textbox', { name: 'latex.find' }), { target: { value: 'second' } })
  fireEvent.click(screen.getByRole('button', { name: 'latex.searchOptions' }))
  fireEvent.click(screen.getByRole('button', { name: 'latex.matchCase' }))
  fireEvent.click(screen.getByText('Switch file'))
  fireEvent.click(screen.getByText('Switch file'))
  input = screen.getByLabelText<HTMLTextAreaElement>('latex.source')
  expect(input.selectionStart).toBe(8)
  expect(input.scrollTop).toBe(45)
  expect(screen.getByRole('textbox', { name: 'latex.find' })).toHaveValue('second')
  fireEvent.click(screen.getByRole('button', { name: 'latex.searchOptions' }))
  expect(screen.getByRole('button', { name: 'latex.matchCase' })).toHaveAttribute('aria-pressed', 'true')
  fireEvent.keyDown(input, { key: 'z', metaKey: true })
  expect(input.value).toBe('first\nsecond')
  fireEvent.click(screen.getByText('Apply AI'))
  expect(input.value).toBe('AI result')
  fireEvent.keyDown(input, { key: 'z', metaKey: true })
  expect(input.value).toBe('first\nsecond')
  fireEvent.keyDown(input, { key: 'z', metaKey: true, shiftKey: true })
  expect(input.value).toBe('AI result')
})

