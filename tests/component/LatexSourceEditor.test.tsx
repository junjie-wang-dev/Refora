it('clamps the cursor and updates status after a shorter external revision without losing undo', async () => {
  const position = vi.fn()
  function Harness() {
    const [value, setValue] = useState('one\ntwo\nthree\nfour\nfive')
    return <><button onClick={() => setValue('one\ntwo\nend')}>Restore revision</button><LatexSourceEditor value={value} onChange={setValue} onPositionChange={position} /></>
  }
  render(<Harness />)
  const input = screen.getByLabelText<HTMLTextAreaElement>('latex.source')
  input.setSelectionRange(19, 19)
  fireEvent.select(input)
  expect(position).toHaveBeenLastCalledWith(5, 1)
  fireEvent.click(screen.getByText('Restore revision'))
  expect(input.selectionStart).toBe(11)
  expect(position).toHaveBeenLastCalledWith(3, 4)
  fireEvent.keyDown(input, { key: 'z', metaKey: true })
  await waitFor(() => expect(input.selectionStart).toBe(19))
  expect(input.value).toBe('one\ntwo\nthree\nfour\nfive')
  expect(position).toHaveBeenLastCalledWith(5, 1)
})
